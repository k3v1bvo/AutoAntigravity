// ── Resolve locale ──────────────────────────────────────────────────────

let _resolvedLang = null;

function _getLang() {
    if (_resolvedLang) return _resolvedLang;
    const langId = vscode.env.language || 'en';
    if (translations[langId]) { _resolvedLang = langId; return langId; }
    const base = langId.split('-')[0];
    if (translations[base]) { _resolvedLang = base; return base; }
    const lower = langId.toLowerCase();
    if (translations[lower]) { _resolvedLang = lower; return lower; }
    _resolvedLang = 'en';
    return 'en';
}

/**
 * Get a translated string by key. Falls back to English, then to the key itself.
 * Supports simple placeholder replacement: %name, %minutes, etc.
 * @param {string} key
 * @param {Object} [args] - Placeholder values, e.g. { minutes: 5 }
 * @returns {string}
 */
function t(key, args) {
    const lang = _getLang();
    let str = (translations[lang] && translations[lang][key])
        || (translations.en && translations.en[key])
        || key;
    if (args) {
        for (const [k, v] of Object.entries(args)) {
            str = str.replace('%' + k, v);
        }
    }
    return str;
}

/** Reset cached locale (for testing) */
function resetLocale() { _resolvedLang = null; }

module.exports = { t, resetLocale, translations };
